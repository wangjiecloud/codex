# 3.1 投资者类型分类标准
"""
基于单笔成交金额划分：

机构 = 超大单
  - 定义: 单笔成交 ≥ 100万元
  - 代表: 公募基金、QFII、保险资金、社保基金

游资/大户 = 大单
  - 定义: 20万元 ≤ 单笔成交 < 100万元
  - 代表: 私募基金、游资、大户、牛散

主力 = 超大单 + 大单
  - 定义: 单笔成交 ≥ 20万元
  - 代表: 所有大额资金

散户 = 小单
  - 定义: 单笔成交 < 4万元
  - 代表: 个人投资者

中单
  - 定义: 4万元 ≤ 单笔成交 < 20万元
  - 代表: 中等规模投资者

补充: 北向资金（沪深港通）= 外资机构流向
"""

